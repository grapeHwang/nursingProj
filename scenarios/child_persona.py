class ChildPersona:
    def __init__(self, name, age, gender, info, instruction):
        self.name = name
        self.age = age
        self.gender = gender
        self.info = info  # 상세 의학 정보
        self.instruction = instruction # 행동 및 대화 규칙

    def get_system_instruction(self):
        return f"""
{self.instruction}

[참고: 환아 상세 배경 정보]
- 성함: {self.name} ({self.gender}, {self.age})
- 주증상: {self.info['chief_concerns']}
- 의학적 상태: {self.info['present_illness']}
- 가족력 및 특이사항: {self.info['history']}
- 현재 상태: 체온 38.0도 이상으로 고열 상태, 목 통증(URI) 있음.
"""

# --- 김 찬 환아 시나리오 정의 ---
